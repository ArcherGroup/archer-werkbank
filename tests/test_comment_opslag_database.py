"""Commentopslag: uitsluitend een eigen scratch PostgreSQL, nooit productie."""
import os
import unittest
import uuid
from pathlib import Path
from urllib.parse import urlsplit
try:
    import psycopg
    from psycopg import sql
except ImportError:
    psycopg = None

DSN = os.environ.get('WERKBANK_TEST_PG_DSN', '')
ROOT = Path(__file__).resolve().parents[1]
MIGRATIE = ROOT / 'supabase/migrations/20261113_comment_ervaring.sql'

@unittest.skipUnless(DSN and psycopg, 'eigen lokale PostgreSQL nodig')
class CommentOpslagTest(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        u = urlsplit(DSN)
        if u.hostname != '127.0.0.1' or u.port != 65439:
            raise RuntimeError('Alleen de eigen scratchcluster is toegestaan')
        cls.dbnaam = 'comment_' + uuid.uuid4().hex[:14]
        with psycopg.connect(DSN, autocommit=True) as admin:
            actual = Path(admin.execute("show data_directory").fetchone()[0]).resolve()
            if actual != (Path.home() / '.hermes/cache/scratch/werkbank-agent-pg-20261112').resolve():
                raise RuntimeError('Andere cluster geweigerd')
            admin.execute(sql.SQL('CREATE DATABASE {}').format(sql.Identifier(cls.dbnaam)))
        cls.dsn = DSN.rsplit('/', 1)[0] + '/' + cls.dbnaam
        with psycopg.connect(cls.dsn, autocommit=True) as db:
            db.execute('CREATE SCHEMA werkbank')
            db.execute('CREATE TABLE werkbank.notities (id bigint generated by default as identity primary key, tekst text, auteur text, parent_id bigint references werkbank.notities(id), client_id text, anker_context jsonb)')
            db.execute("insert into werkbank.notities(tekst,auteur) values ('Bestaand gesprek','Oorspronkelijke auteur')")
            if MIGRATIE.exists(): db.execute(MIGRATIE.read_text())

    def test_eenzelfde_clientbericht_wordt_nooit_twee_rijen(self):
        nonce = 'bericht-' + uuid.uuid4().hex
        with psycopg.connect(self.dsn, autocommit=True) as db:
            for _ in range(2):
                try:
                    db.execute('insert into werkbank.notities(tekst,auteur,client_id) values (%s,%s,%s)', ('Hetzelfde bericht', 'Test', nonce))
                except psycopg.errors.UniqueViolation:
                    pass
            count = db.execute('select count(*) from werkbank.notities where client_id=%s', (nonce,)).fetchone()[0]
            self.assertEqual(count, 1, 'Herhaald netwerkverzoek maakt een dubbele comment')

    def test_bestaande_gesprekken_blijven_ongewijzigd(self):
        with psycopg.connect(self.dsn) as db:
            row = db.execute('select tekst,auteur,parent_id,client_id,anker_context from werkbank.notities where id=1').fetchone()
            self.assertEqual(row, ('Bestaand gesprek', 'Oorspronkelijke auteur', None, None, None))

    def test_migratie_kan_veilig_opnieuw_zonder_datawijziging(self):
        self.assertTrue(MIGRATIE.exists(), 'Featuremigratie ontbreekt')
        with psycopg.connect(self.dsn, autocommit=True) as db:
            before = db.execute('select count(*) from werkbank.notities').fetchone()
            db.execute(MIGRATIE.read_text())
            self.assertEqual(before, db.execute('select count(*) from werkbank.notities').fetchone())
